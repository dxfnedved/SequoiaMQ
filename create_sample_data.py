import os

def create_prediction_file(code, data):
    """创建预测数据文件"""
    os.makedirs("LSTM/predictions", exist_ok=True)
    file_path = f"LSTM/predictions/{code}_prediction.csv"
    
    with open(file_path, 'w') as f:
        f.write(data)
    
    print(f"Created file: {file_path}")

